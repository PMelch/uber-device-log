export type UnityMessageKey = keyof typeof unityCatalogs.en;
const normalize = (locale: string) => locale.replace(/_/g, '-').toLowerCase();
export function resolveUnityMessage(catalogs: Record<string, Partial<Record<string,string>>>, defaultLocale: string, locale: string, key: string): string {
 const selected = normalize(locale), base = selected.split('-')[0]!;
 for (const candidate of [selected, base, normalize(defaultLocale)]) {
  const name = Object.keys(catalogs).find(value => normalize(value) === candidate);
  const value = name ? catalogs[name]?.[key] : undefined;
  if (value?.trim()) return value;
 }
 return key;
}
export function unityTranslate(locale: string, key: UnityMessageKey): string {
 return resolveUnityMessage(unityCatalogs, unityManifest.defaultLocale, locale, key);
}
